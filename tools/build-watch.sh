#!/usr/bin/env bash
# Builds the NavMap watch app. Usage: tools/build-watch.sh [device] [--sim]   (default fr165)
# --sim writes dist/NavMap-sim.prg for the Connect IQ simulator. It receives phone messages but never
# transmits, because the simulator segfaults on any transmit (Garmin bug CIQQA-4579).
# The Maps API key and the NavBridge key are read from ~/.config/navmap/secrets.properties and never committed.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEVICE=fr165
JUNGLE="$ROOT/watch/monkey.jungle"
OUT="$ROOT/dist/NavMap.prg"
for arg in "$@"; do
    case "$arg" in
        --sim) JUNGLE="$ROOT/watch/sim.jungle"; OUT="$ROOT/dist/NavMap-sim.prg" ;;
        *) DEVICE="$arg" ;;
    esac
done
SECRETS="$HOME/.config/navmap/secrets.properties"
KEY_DER="$HOME/.config/navmap/developer_key.der"
export JAVA_HOME="${JAVA_HOME:-$(ls -d "$HOME"/opt/jdk-17* | head -1)}"
export PATH="$JAVA_HOME/bin:$PATH"
SDK_BIN="$("$HOME/bin/connect-iq-sdk-manager" sdk current-path --bin)"

MAPS_API_KEY="$(grep '^MAPS_API_KEY=' "$SECRETS" | cut -d= -f2-)"
# NavBridge answers the watch's /nav requests only with this key, so other phone apps can't read the route.
NAVBRIDGE_TOKEN="$(grep '^NAVBRIDGE_TOKEN=' "$SECRETS" | cut -d= -f2- || true)"
if [ -z "$NAVBRIDGE_TOKEN" ]; then
    echo "NAVBRIDGE_TOKEN missing in $SECRETS (the same key NavBridge is built with)" >&2
    exit 1
fi
cat > "$ROOT/watch/source/Secrets.mc" <<MC
// Generated by tools/build-watch.sh — do not commit.
const MAPS_API_KEY = "$MAPS_API_KEY";
const NAVBRIDGE_TOKEN = "$NAVBRIDGE_TOKEN";
MC

mkdir -p "$ROOT/dist"
# -r (release): leaves out the debug information, which was four fifths of the .prg (124 KB -> 24 KB).
"$SDK_BIN/monkeyc" -f "$JUNGLE" -d "$DEVICE" -y "$KEY_DER" -l 2 -w -r -o "$OUT"
echo "Built $OUT for $DEVICE"
